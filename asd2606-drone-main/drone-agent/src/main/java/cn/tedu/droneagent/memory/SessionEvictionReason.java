package cn.tedu.droneagent.memory;

/**
 * 会话被移出内存的原因。
 *
 * <h2>为什么自定义枚举，不直接用缓存的 RemovalCause</h2>
 * 缓存那边的 {@code RemovalCause} 有五个取值，其中三个（显式删除、被替换、已被回收）
 * <b>都不该归档</b>。把「哪些原因需要归档」这件事用本枚举明确表达出来，
 * 归档方就不需要理解缓存的语义，也不会因为缓存版本升级多出一个取值而悄悄漏掉分支。
 *
 * <p>三种取值**全部都需要归档**——这正是本枚举存在的意义：
 * 能出现在这里的，就是必须落盘的原因。
 *
 * <h2>它在链路里的位置，以及它不负责什么</h2>
 * <p><b>位置</b>：归档调用上的「原因」参数，由 {@link SessionStore} 判断后传给
 * {@link SessionArchiver}，当前只用于日志与测试断言。
 *
 * <ul>
 *   <li><b>不判断原因</b>：到底是过期还是容量淘汰，由缓存给出；
 *       本枚举只负责把「需要归档的原因」列全，不做任何判定。</li>
 *   <li><b>不决定处理方式</b>：三种原因当前处理方式相同（都要落盘），
 *       如果将来需要区别对待，应在这里补语义而不是在调用方堆 if。</li>
 * </ul>
 */
public enum SessionEvictionReason {

    /** 空闲超时被移除 */
    IDLE_TIMEOUT,

    /** 缓存的会话数达到上限，被容量淘汰 */
    SESSION_CAPACITY,

    /** 单个会话的消息数达到上限，被主动移出（先归档再移出） */
    MESSAGE_CAPACITY
}
