-- 删除 user 表遗留的 permission 字段
-- 数据库：drone
-- ============================================================================
-- 执行前提：rbac_seed.sql 已执行，且已经确认 user_role 的数据与 user 行数一致。
-- 本操作【不可逆】，因此先做一份全表快照，回滚时可用：
--   INSERT INTO `user` SELECT * FROM `user_bak`;   （注意会与现有主键冲突，回滚前先清空 user）
-- 确认无误后执行下面两句。
-- ============================================================================

-- 1. 备份（user_bak 若已存在会报错，说明此前备份过，可先 DROP TABLE `user_bak`）
CREATE TABLE `user_bak` AS SELECT * FROM `user`;

-- 2. 删除遗留字段
ALTER TABLE `user` DROP COLUMN `permission`;
