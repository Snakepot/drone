-- ============================================================================
-- 迁移脚本：数字大屏的只读角色（screen）
-- 适用：已建好其它表的库
-- 新库不用执行本脚本 —— schema.sql / data.sql 里已含这个角色
-- ============================================================================
-- 背景见 docs/数字大屏方案.md 4.5：
--   大屏挂在值班室/会议室，token 存在那台机器的浏览器里 —— **谁走过去都能用**。
--   所以它必须是一个**专用只读账号**：最坏情况是「有人看了数据」，
--   而不是「有人删了任务」。这也是为什么不让大屏复用管理员账号 ——
--   复用等于把整个系统的写权限挂在一台没人看着的电脑上。
--
-- ⚠️ 本脚本**只建角色和授权，不建账号**：账号的密码不该出现在仓库里的任何文件里。
--    建账号请走管理端「员工管理 → 新增员工」，角色选「大屏只读」——
--    那样密码由管理员自己设、也走的是现有那套流程（而且账号将来被禁用即可失效）。
--
-- ⚠️ 本脚本可重复执行（用了 INSERT IGNORE）。
-- ============================================================================

INSERT IGNORE INTO `role` (`code`, `name`, `description`, `status`) VALUES
  ('screen', '大屏只读', '值班室/会议室大屏专用，只能看统计与列表，不能改任何东西', 1);

-- 只授「统计要看的那几个读权限」，一个写权限都不给：
--   task:list    任务总览与在飞位置
--   device:list  设备总数/状态/累计架次
--   alert:list   告警分布与最近告警
--   staff:list   人员在线情况
--   route:list   点位与航线数量
--   zone:list    禁飞区数量
-- （geo 那三个数字对**登录用户**都可见，但明细仍然要这两个权限，
--   所以这里给上，让大屏能显示完整的资源概况）
INSERT IGNORE INTO `role_permission` (`role_id`, `permission_id`)
SELECT r.id, p.id
FROM `role` r JOIN `permission` p
WHERE r.code = 'screen'
  AND p.code IN ('task:list', 'device:list', 'alert:list', 'staff:list', 'route:list', 'zone:list');

