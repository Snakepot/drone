package cn.tedu.drone.task.service;

/**
 * 待派发任务的归因采样（见 {@code docs/业务分析方案.md} 2.7）。
 *
 * <h2>它要回答的问题，事后是算不出来的</h2>
 * 任务卡在待派发，「当时有没有空闲的飞手和设备」是**那一刻的事实**。
 * 事后去查只能看到现在的资源池 —— 所以必须在当时就把结论记下来。
 * 这个 Service 就是做那一刻的判断。
 *
 * <h2>判断依据与派发时的校验**同源**</h2>
 * 「可派飞手数」= 派发下拉里那些人 − 时间窗内已被占住的。
 * 两边用的重叠条件必须是同一份，否则会出现
 * 「派发时说能派、归因却说缺人」这种自相矛盾，比没有这个功能更糟。
 */
public interface DispatchBlockService {

    /**
     * 给当前所有待派发任务打一次归因点。
     *
     * <p>由定时任务调用（也便于测试直接调）。
     *
     * <p><b>不是每次都写库</b>：同一个任务如果原因没变、且上一次采样还没过
     * {@code repeat-minutes}，就跳过 —— 否则一天下来「一个任务被卡住」会变成
     * 144 条一模一样的记录，表白涨、趋势图也看不出东西。
     *
     * @return 本次真正写进去的条数（跳过的不算）
     */
    int samplePendingTasks();

    /**
     * 扫一轮的上限：一次最多处理多少条待派发任务。
     *
     * <p>和超时释放那类扫描同一个考虑：分批、不追求一轮扫完，
     * 免得某天积压几百条时这一轮卡住（它只是个采样任务，晚一轮没影响）。
     */
    int SCAN_BATCH_SIZE = 200;
}
